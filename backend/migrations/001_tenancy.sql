-- =====================================================================================================
-- 001_tenancy.sql: organizations -> teams -> memberships, and team_id on every team-owned table.
--
-- PostgreSQL 14+ / Supabase. Idempotent: safe to re-run. Run as the table owner (Supabase: postgres).
-- Non-destructive: only adds tables, columns, constraints and triggers. Existing rows land in the
-- default team (id 1) through a column DEFAULT, so there is no UPDATE backfill (the append-only
-- triggers on audit_log / agent_runs would reject one).
--
-- Conventions follow backend/app/db.py: INTEGER identity keys, TEXT UTC timestamps
-- 'YYYY-MM-DD HH24:MI:SS', INTEGER 0/1 flags (the SQLite mirror and the API depend on these).
-- =====================================================================================================
BEGIN;
-- Fail fast instead of queueing behind a long transaction (a queued ALTER blocks all later traffic).
SET LOCAL lock_timeout = '5s';

-- Helper functions live here. The schema is not exposed through the Supabase Data API.
CREATE SCHEMA IF NOT EXISTS smartlab;

-- ------------------------------------------------------------------------------- tenancy tables
CREATE TABLE IF NOT EXISTS public.organizations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS public.teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
    name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
    slug TEXT NOT NULL CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    description TEXT CHECK (description IS NULL OR length(description) <= 500),
    -- New sign-ups join their organization's default team (smartlab.enroll_in_default_team).
    is_default INTEGER NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
    -- Teams are archived, never deleted: audit rows reference them.
    archived_at TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'),
    UNIQUE (organization_id, slug)  -- also serves as the index for the organization_id foreign key
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_teams_one_default ON public.teams (organization_id) WHERE is_default = 1;

CREATE TABLE IF NOT EXISTS public.team_memberships (
    team_id INTEGER NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'admin', 'member', 'viewer')),
    created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (team_id, user_id)  -- leading team_id: "members of team X"
);
CREATE INDEX IF NOT EXISTS idx_team_memberships_user ON public.team_memberships (user_id);  -- "teams of user Y"

CREATE TABLE IF NOT EXISTS public.organization_invitations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INTEGER NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    team_id INTEGER REFERENCES public.teams(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'admin', 'member', 'viewer')),
    token_hash TEXT NOT NULL UNIQUE,
    invited_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS'),
    expires_at TEXT NOT NULL,
    used_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_invitations_token ON public.organization_invitations (token_hash);
CREATE INDEX IF NOT EXISTS idx_invitations_org_email ON public.organization_invitations (organization_id, email);

-- ------------------------------------------------------------------------------- default tenant
-- Pinned to id 1 to match the existing organization_id DEFAULT 1 rows and SMARTLAB_DEFAULT_ORG_ID.
INSERT INTO public.organizations (id, name, slug) VALUES (1, 'Default organization', 'default')
ON CONFLICT (id) DO NOTHING;
INSERT INTO public.teams (id, organization_id, name, slug, is_default) VALUES (1, 1, 'General', 'general', 1)
ON CONFLICT (id) DO NOTHING;
-- Explicit ids do not advance identity sequences; without this the next INSERT would collide with id 1.
SELECT setval(pg_get_serial_sequence('public.organizations', 'id'), GREATEST((SELECT MAX(id) FROM public.organizations), 1));
SELECT setval(pg_get_serial_sequence('public.teams', 'id'), GREATEST((SELECT MAX(id) FROM public.teams), 1));

-- ------------------------------------------------------------------------------- users
-- users.role ('admin' | 'member') becomes the organization role. Org admins own every team in their org.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS organization_id INTEGER NOT NULL DEFAULT 1;
-- Bridge for Supabase Auth: when set, auth.uid() resolves to this account (smartlab.current_user_id()).
-- Kept without a foreign key to auth.users so the script also runs on plain PostgreSQL.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS auth_user_id UUID;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_auth_user_id ON public.users (auth_user_id) WHERE auth_user_id IS NOT NULL;

-- Existing accounts join the default team once. A deliberately removed member is not re-added on re-run,
-- because this only inserts for users with no membership at all.
INSERT INTO public.team_memberships (team_id, user_id, role)
SELECT 1, u.id, CASE WHEN u.role = 'admin' THEN 'owner' ELSE 'member' END
  FROM public.users u
 WHERE NOT EXISTS (SELECT 1 FROM public.team_memberships m WHERE m.user_id = u.id)
ON CONFLICT DO NOTHING;

-- ------------------------------------------------------------------------------- team_id columns
-- A constant DEFAULT is metadata-only on PostgreSQL 11+: no table rewrite, no row locks held for long.
ALTER TABLE public.documents       ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.reagents        ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.troubleshooting ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.equipment       ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.projects        ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.experiments     ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.datasets        ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.comments        ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.shared_files    ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.chat_messages   ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.agent_uploads   ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.agent_runs      ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
-- Sign-up and password-reset events belong to no team. Existing rows keep 1: dropping the default
-- does not touch the value already stored for them.
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name = 'audit_log' AND column_name = 'team_id') THEN
        ALTER TABLE public.audit_log ADD COLUMN team_id INTEGER DEFAULT 1;
        ALTER TABLE public.audit_log ALTER COLUMN team_id DROP DEFAULT;
    END IF;
END $$;

-- Duplicate-upload detection becomes per team. Build the new unique index before dropping the old one,
-- so there is never a moment without a uniqueness guarantee.
CREATE UNIQUE INDEX IF NOT EXISTS uq_documents_team_sha256 ON public.documents (team_id, sha256);
ALTER TABLE public.documents DROP CONSTRAINT IF EXISTS documents_sha256_key;

-- ------------------------------------------------------------------------------- foreign keys
-- NOT VALID: takes a brief lock and checks only new rows. 003_indexes.sql validates existing rows
-- later, under a lock that allows concurrent writes.
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['documents', 'reagents', 'troubleshooting', 'equipment', 'projects', 'experiments',
                             'datasets', 'comments', 'shared_files', 'chat_messages', 'agent_uploads',
                             'agent_runs', 'audit_log'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                        WHERE conrelid = format('public.%I', t)::regclass AND conname = t || '_team_id_fkey') THEN
            EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (team_id) '
                           'REFERENCES public.teams(id) NOT VALID', t, t || '_team_id_fkey');
        END IF;
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conrelid = 'public.users'::regclass AND conname = 'users_organization_id_fkey') THEN
        ALTER TABLE public.users ADD CONSTRAINT users_organization_id_fkey
            FOREIGN KEY (organization_id) REFERENCES public.organizations(id) NOT VALID;
    END IF;
END $$;

-- ------------------------------------------------------------------------------- team_id is immutable
-- A row never moves between teams. Besides keeping audit history honest, this protects the per-process
-- RAG scope cache (rag/engine.py), which may hold a stale chunk set but must never admit another team's
-- chunk. Move data by re-creating it in the other team.
CREATE OR REPLACE FUNCTION smartlab.forbid_team_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    IF NEW.team_id IS DISTINCT FROM OLD.team_id THEN
        RAISE EXCEPTION '%.team_id cannot change; re-create the row in the other team', TG_TABLE_NAME
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
    -- audit_log and agent_runs already reject every UPDATE (PG_AUDIT_GUARD in db.py).
    FOREACH t IN ARRAY ARRAY['documents', 'reagents', 'troubleshooting', 'equipment', 'projects', 'experiments',
                             'datasets', 'comments', 'shared_files', 'chat_messages', 'agent_uploads'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger
                        WHERE tgrelid = format('public.%I', t)::regclass AND tgname = t || '_team_immutable') THEN
            EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OF team_id ON public.%I '
                           'FOR EACH ROW EXECUTE FUNCTION smartlab.forbid_team_change()', t || '_team_immutable', t);
        END IF;
    END LOOP;
END $$;

-- ------------------------------------------------------------------------------- last owner guard
-- A team keeps at least one explicit owner (org admins are implicit owners, but they can change).
CREATE OR REPLACE FUNCTION smartlab.keep_one_owner() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    IF OLD.role = 'owner' AND (TG_OP = 'DELETE' OR NEW.role <> 'owner' OR NEW.team_id <> OLD.team_id)
       AND EXISTS (SELECT 1 FROM public.teams t WHERE t.id = OLD.team_id)  -- not a cascade from a team delete
       AND NOT EXISTS (SELECT 1 FROM public.team_memberships m
                        WHERE m.team_id = OLD.team_id AND m.role = 'owner' AND m.user_id <> OLD.user_id) THEN
        RAISE EXCEPTION 'team % must keep at least one owner', OLD.team_id USING ERRCODE = 'check_violation';
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;

DROP TRIGGER IF EXISTS team_memberships_keep_owner ON public.team_memberships;
CREATE TRIGGER team_memberships_keep_owner BEFORE UPDATE OR DELETE ON public.team_memberships
    FOR EACH ROW EXECUTE FUNCTION smartlab.keep_one_owner();

COMMIT;
