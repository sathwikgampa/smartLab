-- =====================================================================================================
-- 005_generated_images.sql: SmartLab Visualizer generation log under team tenancy and row-level security.
--
-- Requires 001_tenancy.sql and 002_rls.sql. Idempotent. Run as the table owner (Supabase: postgres).
-- The app creates generated_images itself on start-up (SCHEMA in backend/app/db.py, append-only trigger
-- from PG_AUDIT_GUARD); the CREATE TABLE below matches it so this script also runs before the first start.
-- =====================================================================================================
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS public.generated_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INTEGER NOT NULL DEFAULT 1,
    user_id INTEGER REFERENCES public.users(id),
    actor TEXT,
    project_id INTEGER REFERENCES public.projects(id) ON DELETE SET NULL,
    prompt TEXT NOT NULL,           -- what the researcher typed (sanitised)
    final_prompt TEXT,              -- what the provider received (with the style template)
    style TEXT NOT NULL,
    aspect_ratio TEXT NOT NULL,
    provider TEXT,
    model TEXT,
    status TEXT NOT NULL,           -- succeeded | blocked | failed
    error TEXT,
    stored_name TEXT,               -- PNG in UPLOAD_DIR/generated
    mime_type TEXT,
    width INTEGER,
    height INTEGER,
    size_bytes INTEGER,
    sha256 TEXT,                    -- integrity check for the stored file
    duration_ms INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(timezone('UTC', statement_timestamp()), 'YYYY-MM-DD HH24:MI:SS')
);

-- Status values are fixed; NOT VALID so existing rows are not re-checked under lock.
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.generated_images'::regclass
                    AND conname = 'generated_images_status_check') THEN
        ALTER TABLE public.generated_images ADD CONSTRAINT generated_images_status_check
            CHECK (status IN ('succeeded', 'blocked', 'failed')) NOT VALID;
    END IF;
END $$;

-- ------------------------------------------------------------------------------- tenancy
ALTER TABLE public.generated_images ADD COLUMN IF NOT EXISTS team_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE public.generated_images ALTER COLUMN team_id SET DEFAULT COALESCE(smartlab.current_team_id(), 1);
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.generated_images'::regclass
                    AND conname = 'generated_images_team_id_fkey') THEN
        ALTER TABLE public.generated_images ADD CONSTRAINT generated_images_team_id_fkey
            FOREIGN KEY (team_id) REFERENCES public.teams(id) NOT VALID;
    END IF;
END $$;

-- History per user (ORDER BY id DESC) and the team gallery.
CREATE INDEX IF NOT EXISTS idx_generated_images_team_user ON public.generated_images (team_id, user_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_generated_images_team_created ON public.generated_images (team_id, created_at);

-- ------------------------------------------------------------------------------- append-only
-- Same guard as audit_log / agent_runs (smartlab_append_only() is installed by the app's PG_AUDIT_GUARD).
DO $$ BEGIN
    IF to_regprocedure('public.smartlab_append_only()') IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM pg_trigger WHERE tgname = 'generated_images_append_only'
           AND tgrelid = 'public.generated_images'::regclass) THEN
        CREATE TRIGGER generated_images_append_only BEFORE UPDATE OR DELETE ON public.generated_images
            FOR EACH ROW EXECUTE FUNCTION public.smartlab_append_only();
    END IF;
END $$;

-- ------------------------------------------------------------------------------- row-level security
-- Team viewers may read; members may generate. No UPDATE or DELETE policy, so RLS refuses both.
ALTER TABLE public.generated_images ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS generated_images_select ON public.generated_images;
DROP POLICY IF EXISTS generated_images_insert ON public.generated_images;
CREATE POLICY generated_images_select ON public.generated_images FOR SELECT
    USING (team_id = ANY ((SELECT smartlab.team_ids('viewer'))::integer[]));
CREATE POLICY generated_images_insert ON public.generated_images FOR INSERT
    WITH CHECK (team_id = ANY ((SELECT smartlab.team_ids('member'))::integer[]));

GRANT SELECT, INSERT ON public.generated_images TO smartlab_app;
DO $$ BEGIN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO smartlab_app',
                   pg_get_serial_sequence('public.generated_images', 'id'));
END $$;

COMMIT;
